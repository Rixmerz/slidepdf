"""Regenerates src/metrics.rs: advance widths (1/1000 em) for WinAnsi codes
32..255. Base-14 widths come from the metric-compatible Liberation fonts;
Calibri widths from its metric-compatible clone Carlito (Google Fonts, OFL).

    uv run --with fonttools python scripts/gen_metrics.py <liberation-dir> <carlito-dir> > src/metrics.rs
"""
import sys
from fontTools.ttLib import TTFont

lib, carlito = sys.argv[1], sys.argv[2]
fonts = [
    ("HELVETICA", f"{lib}/LiberationSans-Regular.ttf"),
    ("HELVETICA_BOLD", f"{lib}/LiberationSans-Bold.ttf"),
    ("HELVETICA_OBLIQUE", f"{lib}/LiberationSans-Italic.ttf"),
    ("HELVETICA_BOLD_OBLIQUE", f"{lib}/LiberationSans-BoldItalic.ttf"),
    ("TIMES_ROMAN", f"{lib}/LiberationSerif-Regular.ttf"),
    ("TIMES_BOLD", f"{lib}/LiberationSerif-Bold.ttf"),
    ("TIMES_ITALIC", f"{lib}/LiberationSerif-Italic.ttf"),
    ("TIMES_BOLD_ITALIC", f"{lib}/LiberationSerif-BoldItalic.ttf"),
    ("CALIBRI", f"{carlito}/Carlito-Regular.ttf"),
    ("CALIBRI_BOLD", f"{carlito}/Carlito-Bold.ttf"),
    ("CALIBRI_ITALIC", f"{carlito}/Carlito-Italic.ttf"),
    ("CALIBRI_BOLD_ITALIC", f"{carlito}/Carlito-BoldItalic.ttf"),
]
print("//! Glyph advance widths, indexed by WinAnsi code - 32 (units: 1/1000 em).")
print("//! Generated by scripts/gen_metrics.py from metric-compatible fonts:")
print("//! Liberation (Helvetica, Times) and Carlito (Calibri).\n")
for name, path in fonts:
    t = TTFont(path)
    cmap, hm, upm = t.getBestCmap(), t["hmtx"], t["head"].unitsPerEm
    ws = []
    for b in range(32, 256):
        try:
            ch = bytes([b]).decode("cp1252")
        except UnicodeDecodeError:
            ws.append(0)
            continue
        g = cmap.get(ord(ch))
        ws.append(round(hm[g][0] * 1000 / upm) if g else 0)
    print(f"pub const {name}: [u16; 224] = {ws};")
